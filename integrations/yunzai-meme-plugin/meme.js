/**
 * 校验静态列表是否与本地 meme 数据一致（页大小相同且全部 key 一一对应）。
 * 不一致时返回 null，调用方回退到 POST /memes/render_list。
 * @param {object|null} manifest
 * @param {string[]} memeKeys 本地（实时接口）给出的 meme key 列表
 * @param {number} pageSize 本地分页大小
 * @returns {{version: string, pages: Array<{page: number, file: string, keys: string[]}>}|null}
 */
function resolveStaticList(manifest, memeKeys, pageSize) {
  if (!manifest) return null
  if (Number(manifest.pageSize) !== pageSize) {
    logger.debug(`静态 meme 列表页大小不匹配（${manifest.pageSize} != ${pageSize}），回退到实时渲染`)
    return null
  }
  const pages = (manifest.pages || [])
    .map(page => ({
      page: Number(page?.page),
      file: safeStaticPageFile(page),
      keys: Array.isArray(page?.keys) ? page.keys.filter(key => typeof key === 'string') : []
    }))
    .filter(page => Number.isInteger(page.page) && page.file && page.keys.length > 0)
    .sort((a, b) => a.page - b.page)
  if (pages.length === 0) return null

  const flat = pages.flatMap(page => page.keys)
  if (flat.length !== memeKeys.length) {
    logger.debug(`静态 meme 列表数量不匹配（${flat.length} != ${memeKeys.length}），回退到实时渲染`)
    return null
  }
  const expected = new Set(memeKeys)
  if (flat.length !== expected.size || flat.some(key => !expected.has(key))) {
    logger.debug('静态 meme 列表内容与当前 meme 数据不一致，回退到实时渲染')
    return null
  }

  return {
    version: String(manifest.version || manifest.signature || 'na').slice(0, 12),
    pages
  }
}

function safeStaticPageFile(page) {
  const name = typeof page?.file === 'string' ? page.file.split('/').pop() : ''
  return /^[A-Za-z0-9._-]+\.(png|jpe?g|gif|webp)$/i.test(name) ? name : ''
}

