  async init(forceRefresh = false) {
    mkdirs(memeDataDir)
    infos = readJsonObject(path.join(memeDataDir, 'infos.json'))
    keyMap = readJsonObject(path.join(memeDataDir, 'keyMap.json'))

    let remoteInfosLoaded = false
    let remoteKeyMapLoaded = false

    if (forceRefresh || !isNonEmptyObject(infos) || !isNonEmptyObject(keyMap)) {
      logger.mark(`yunzai-meme 正在${forceRefresh ? '刷新' : '拉取'}远程元数据`)
      try {
        const [remoteInfos, remoteKeyMap] = await Promise.all([
          fetchJson(`${baseUrl}/memes/static/infos.json`),
          fetchJson(`${baseUrl}/memes/static/keyMap.json`)
        ])
        if (!isNonEmptyObject(remoteInfos)) throw new Error('infos.json 内容为空')
        if (!isNonEmptyObject(remoteKeyMap)) throw new Error('keyMap.json 内容为空')
        infos = remoteInfos
        keyMap = remoteKeyMap
        remoteInfosLoaded = true
        remoteKeyMapLoaded = true
        await Promise.all([
          writeJsonAtomic(path.join(memeDataDir, 'infos.json'), infos),
          writeJsonAtomic(path.join(memeDataDir, 'keyMap.json'), keyMap)
        ])
      } catch (error) {
        logger.error(`yunzai-meme 元数据更新失败，继续使用本地缓存：${error.message}`)
      }
    }

    if (!isNonEmptyObject(infos) || !isNonEmptyObject(keyMap)) {
      logger.warn('静态元数据不可用，正在通过 info 接口重建索引')
      const keys = await fetchJson(`${baseUrl}/memes/keys`)
      if (!Array.isArray(keys) || keys.length === 0) {
        throw new Error('无法获取 meme key 列表')
      }

      const infoEntries = await mapWithConcurrency(keys, 8, async key => {
        try {
          const info = await fetchJson(`${baseUrl}/memes/${key}/info`)
          return [key, info]
        } catch (error) {
          logger.error(`获取 ${key} 详情失败：${error.message}`)
          return null
        }
      })

      const rebuiltInfos = {}
      const rebuiltKeyMap = {}
      for (const entry of infoEntries.filter(Boolean)) {
        const [key, info] = entry
        if (!info || !Array.isArray(info.keywords)) continue
        rebuiltInfos[key] = info
        for (const keyword of info.keywords) rebuiltKeyMap[keyword] = key
      }

      if (!isNonEmptyObject(rebuiltInfos) || !isNonEmptyObject(rebuiltKeyMap)) {
        throw new Error('重建 meme 元数据失败')
      }
      infos = rebuiltInfos
      keyMap = rebuiltKeyMap
      await Promise.all([
        writeJsonAtomic(path.join(memeDataDir, 'infos.json'), infos),
        writeJsonAtomic(path.join(memeDataDir, 'keyMap.json'), keyMap)
      ])
      remoteInfosLoaded = true
      remoteKeyMapLoaded = true
    }

    const memeRules = Object.keys(keyMap)
      .sort((a, b) => b.length - a.length)
      .map(key => ({
        reg: forceSharp ? `^#${escapeRegExp(key)}` : `^#?${escapeRegExp(key)}`,
        fnc: 'memes'
      }))
    const randomMemeRule = buildRandomMemeRule(keyMap)
    this.rule = [...commandRules, ...(randomMemeRule ? [randomMemeRule] : []), ...memeRules]

    const refreshed = remoteInfosLoaded && remoteKeyMapLoaded
    if (refreshed) clearListCacheFiles()
    return { refreshed }
  }

