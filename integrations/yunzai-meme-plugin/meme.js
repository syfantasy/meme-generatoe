function detectImageExtension(buffer) {
  if (buffer.length >= 8 && buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'png'
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) return 'jpg'
  if (buffer.length >= 6 && ['GIF87a', 'GIF89a'].includes(buffer.subarray(0, 6).toString('ascii'))) return 'gif'
  if (buffer.length >= 12 && buffer.subarray(0, 4).toString('ascii') === 'RIFF' && buffer.subarray(8, 12).toString('ascii') === 'WEBP') return 'webp'
  return null
}

function isValidImageFile(file) {
  try {
    const stat = fs.statSync(file)
    if (!stat.isFile() || stat.size < minimumImageBytes) return false
    const fd = fs.openSync(file, 'r')
    try {
      const header = Buffer.alloc(16)
      const bytesRead = fs.readSync(fd, header, 0, header.length, 0)
      return Boolean(detectImageExtension(header.subarray(0, bytesRead)))
    } finally {
      fs.closeSync(fd)
    }
  } catch {
    return false
  }
}

function clearListCacheFiles(activeVersion = '') {
  if (!fs.existsSync(memeDataDir)) return
  const activePrefix = activeVersion ? `render_list_v${listCacheVersion}_${activeVersion}_` : ''
  for (const filename of fs.readdirSync(memeDataDir)) {
    if (filename.startsWith('.render-list-')) {
      const file = path.join(memeDataDir, filename)
      try {
        if (Date.now() - fs.statSync(file).mtimeMs > 10 * 60 * 1000) fs.unlinkSync(file)
      } catch {}
      continue
    }
    if (!filename.startsWith('render_list')) continue
    if (activePrefix && filename.startsWith(activePrefix)) continue
    try {
      fs.unlinkSync(path.join(memeDataDir, filename))
    } catch (error) {
      logger.warn(`清理旧列表缓存失败 ${filename}：${error.message}`)
    }
  }
}

function findValidListCache(cacheBase) {
  for (const extension of ['png', 'jpg', 'gif', 'webp']) {
    const file = `${cacheBase}.${extension}`
    if (!fs.existsSync(file)) continue
    if (isValidImageFile(file)) return file
    try {
      fs.unlinkSync(file)
    } catch {}
  }
  return null
}

/**
 * 取回列表页图片：优先使用服务端预渲染的静态地址，不可用时回退到实时渲染接口。
 * @param {string[]} pageKeys 该页的 meme key（回退实时渲染时使用）
 * @param {number} page 页码
 * @param {string} cacheTag 缓存标识（使用静态列表时含其版本号，便于换版后失效）
 * @param {{url: string}|null} staticSource 静态图片地址
 */
async function getMemeListPage(pageKeys, page, cacheTag, staticSource = null) {
  const cacheBase = path.join(memeDataDir, `render_list_v${listCacheVersion}_${cacheTag}_p${page}`)
  const cachedFile = findValidListCache(cacheBase)
  if (cachedFile) return cachedFile

  if (listRenderTasks.has(cacheBase)) return await listRenderTasks.get(cacheBase)

  const renderTask = (async () => {
    let tempFile = ''
    try {
      let resultBuffer = staticSource?.url ? await fetchStaticListImage(staticSource.url) : null
      if (!resultBuffer) resultBuffer = await renderMemeListPage(pageKeys)

      const extension = detectImageExtension(resultBuffer)
      if (resultBuffer.length < minimumImageBytes || !extension) {
        throw new Error(`列表服务返回的不是有效图片（${resultBuffer.length} bytes）`)
      }

      const finalFile = `${cacheBase}.${extension}`
      tempFile = path.join(memeDataDir, `.render-list-${process.pid}-${Date.now()}.tmp`)
      await fs.promises.writeFile(tempFile, resultBuffer)
      await fs.promises.rename(tempFile, finalFile)
      tempFile = ''
      return finalFile
    } finally {
      if (tempFile) {
        try {
          await fs.promises.unlink(tempFile)
        } catch {}
      }
    }
  })()

  listRenderTasks.set(cacheBase, renderTask)
  try {
    return await renderTask
  } finally {
    listRenderTasks.delete(cacheBase)
  }
}

