  async memesList(e) {
    try {
      const memeKeys = Object.keys(infos)
        .filter(key => infos[key]?.params_type)
        .sort((a, b) => {
          const nameA = infos[a]?.keywords?.[0] || a
          const nameB = infos[b]?.keywords?.[0] || b
          return nameA.localeCompare(nameB, 'zh-CN')
        })

      if (memeKeys.length === 0) {
        await e.reply('meme 数据尚未加载，请先发送「meme更新」', true)
        return true
      }

      const pageMatch = e.msg.match(/列表\s*(\d+)?$/)
      const requestedPage = pageMatch?.[1] ? Number(pageMatch[1]) : null
      // 服务端构建镜像时已预渲染的列表优先使用（GET /memes/static/list/manifest.json），
      // meme 集合或页大小不一致时自动回退到实时渲染。
      const staticList = resolveStaticList(await fetchStaticListManifest(), memeKeys, listPageSize)
      if (staticList) logger.debug(`使用静态 meme 列表 version=${staticList.version} pages=${staticList.pages.length}`)
      const totalPages = staticList ? staticList.pages.length : Math.ceil(memeKeys.length / listPageSize)
      if (requestedPage !== null && (!Number.isInteger(requestedPage) || requestedPage < 1 || requestedPage > totalPages)) {
        await e.reply(`页码无效，当前共有 ${totalPages} 页`, true)
        return true
      }

      const listVersion = buildListVersion(memeKeys)
      const cacheTag = staticList ? `static${staticList.version}_${listVersion}` : listVersion
      clearListCacheFiles(cacheTag)
      const pages = requestedPage === null
        ? Array.from({ length: totalPages }, (_, index) => index + 1)
        : [requestedPage]

      if (pages.length > 1) {
        await e.reply(`正在准备 ${memeKeys.length} 个 meme，共 ${totalPages} 页，请稍候……`)
      }

      const forwardNodes = []
      for (const page of pages) {
        const start = (page - 1) * listPageSize
        const staticPage = staticList ? staticList.pages[page - 1] : null
        const pageKeys = staticPage ? staticPage.keys : memeKeys.slice(start, start + listPageSize)
        try {
          const resultFileLoc = await getMemeListPage(
            pageKeys,
            page,
            cacheTag,
            staticPage ? { url: `${baseUrl}/memes/static/list/${staticPage.file}` } : null
          )
          forwardNodes.push(makeForwardNode(
            e,
            `meme 列表第 ${page}/${totalPages} 页（${start + 1}-${start + pageKeys.length}，共 ${memeKeys.length} 个）`,
            segment.image(path.resolve(resultFileLoc))
          ))
        } catch (error) {
          logger.error(`meme 列表第 ${page} 页生成失败：${error.message}`)
          forwardNodes.push(makeForwardNode(
            e,
            `meme 列表第 ${page}/${totalPages} 页生成失败：${error.message}`
          ))
        }
      }

      await sendForwardNodes(e, forwardNodes)
      return true
    } catch (error) {
      console.error('memesList error:', error)
      await e.reply('获取表情包列表失败：' + error.message, true)
      return true
    }
  }

